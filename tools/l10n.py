#!/usr/bin/env python3
"""Build languages/flurfunk-<locale>.l10n.php (WordPress 6.5+ PHP translation files) from
tools/translations/<locale>.json. Context strings use "context\u0004text" as key."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
q = lambda s: "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"
for src in sorted((root / 'tools' / 'translations').glob('*.json')):
    loc = src.stem
    data = json.loads(src.read_text())
    nul = lambda x: x.replace(chr(4), chr(39) + ' . chr(4) . ' + chr(39)).replace(chr(0), chr(39) + ' . chr(0) . ' + chr(39))
    msgs = "\n".join(f"\t\t{nul(q(k))} => {nul(q(v))}," for k, v in sorted(data.items()))
    out = f"""<?php
defined( 'ABSPATH' ) || exit;
// Generated by tools/l10n.py from tools/translations/{loc}.json – do not edit by hand.
return array(
\t'domain'       => 'flurfunk',
\t'language'     => '{loc}',
\t'plural-forms' => 'nplurals=2; plural=(n != 1);',
\t'messages'     => array(
{msgs}
\t),
);
"""
    (root / 'languages' / f'flurfunk-{loc}.l10n.php').write_text(out)
    print(loc, len(data))
