#!/usr/bin/env python3
"""Collect the interface strings from assets/*.js into inc/strings.php, so translation tools
(and WordPress language packs) find them as normal __() calls. Run after changing JS texts."""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
found = []
for js in sorted((root / 'assets').glob('*.js')):
    for m in re.finditer(r"\bt\(\s*'((?:[^'\\]|\\.)*)'", js.read_text()):
        s = m.group(1).replace("\\'", "'")
        if s not in found:
            found.append(s)
php = lambda s: s.replace('\\', '\\\\').replace("'", "\\'")
lines = [f"\t\t'{php(s)}' => __( '{php(s)}', 'flurfunk' )," for s in found]
out = """<?php
/**
 * Interface strings for the JavaScript, keyed by their English text.
 * Generated by tools/strings.py from assets/*.js – do not edit by hand.
 *
 * @package Flurfunk
 */

namespace Flurfunk\\Strings;

defined( 'ABSPATH' ) || exit;

/**
 * All strings, translated.
 *
 * @return array<string,string>
 */
function all(): array {
	// phpcs:disable WordPress.WP.I18n.MissingTranslatorsComment
	return array(
""" + "\n".join(lines) + """
	);
}
"""
(root / 'inc' / 'strings.php').write_text(out)
print(len(found), 'strings')
